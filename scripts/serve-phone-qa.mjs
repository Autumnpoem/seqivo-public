import {createCore} from '../server/core.mjs';
import {createHub} from '../server/hub/http.mjs';
import {mkdtemp,readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
const dir=await mkdtemp(join(tmpdir(),'tuijin-phone-qa-'));
const core=await createCore({dataDir:join(dir,'node'),pluginDir:resolve('plugins'),files:false});
const hub=await createHub({dataDir:join(dir,'hub'),distDir:resolve('dist'),port:4328});
const admin=hub.store.bootstrap('phone-qa');const owner=hub.store.authenticate((await readFile(admin.tokenPath,'utf8')).trim());
const p=core.store.project({name:'手机端验收',goal:'检查 Safari 下真实同步、状态和交付偏差展示'});
const a=core.store.createTask({projectId:p.id,title:'真实远程同步',goal:'从 Hub 读取电脑上保存的任务',summary:'任务已通过真实 HTTP 同步，等待手机界面验收。',example:'电脑更新后，手机能看到最新进度。',criteria:['Safari 中能读取任务详情'],sourceConversation:{provider:'codex',conversationId:'qa',label:'手机验收'}});
core.store.updateTask(a.id,{status:'submitted',approach:'电脑通过主动连接同步，手机按项目授权读取。'},a.revision);
core.store.createTask({projectId:p.id,title:'公网与实体设备验收',goal:'域名与服务器确定后，用真实手机连接',summary:'等待用户提供服务器或域名。',criteria:['真实手机 HTTPS 访问']});
let b=core.store.createTask({projectId:p.id,title:'检查交付偏差',goal:'页面应连接真实业务接口',summary:'已发现当前产物只有离线演示',criteria:['真实接口写入后可重新读取']});core.store.review(b.id,{expectedRevision:b.revision,decision:'fail',summary:'只有离线演示，尚未接入业务系统。'});
const pairing=hub.store.createPairing(owner,{role:'node',projectIds:[p.id]});await core.request('POST','/api/remote/connect',{url:hub.url,pairingCode:pairing.code,projectIds:[p.id]});
const phone=hub.store.createPairing(owner,{role:'viewer',projectIds:[p.id],ttlSeconds:3600});
await writeFile(join(dir,'qa-access.json'),JSON.stringify({url:hub.url,code:phone.code,dataDir:dir}),{mode:0o600});
console.log(JSON.stringify({url:hub.url,accessFile:join(dir,'qa-access.json')}));
const close=async()=>{await core.close();await hub.close();process.exit(0);};process.on('SIGINT',close);process.on('SIGTERM',close);

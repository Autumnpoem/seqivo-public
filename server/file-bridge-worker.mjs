import { mkdir, readdir, readFile, writeFile, rename, lstat, realpath, open } from 'node:fs/promises';
import { constants } from 'node:fs';
import { isAbsolute, join, sep } from 'node:path';
import { randomUUID, createHash } from 'node:crypto';

const MAX_IPC_BYTES = 8 * 1024 * 1024;
const within = (path, parent) => path.startsWith(parent + sep);
const bounded = value => Buffer.byteLength(JSON.stringify(value)) <= MAX_IPC_BYTES;
const marker = '<!-- Generated by Seqivo file reporting -->';
const generated = /<!-- Seqivo file reporting v(\d+) sha256:([a-f0-9]{64}) -->/;
const rulePaths = { codex: 'AGENTS.md', claude: 'CLAUDE.md' };

async function regularText(path) {
  let handle;
  try { handle = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
  try {
    const stat = await handle.stat();
    if (!stat.isFile() || stat.size > 1_000_000) throw Error('文件不是普通文件或过大');
    return await handle.readFile('utf8');
  } finally { await handle.close(); }
}

async function safeDirectory(path) {
  try {
    const stat = await lstat(path);
    if (!stat.isDirectory() || stat.isSymbolicLink()) throw Error('Unsafe project metadata directory');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    await mkdir(path, { recursive: true });
  }
}

async function atomic(path, value) {
  const temp = path + '.' + randomUUID() + '.tmp';
  await writeFile(temp, value, { mode: 0o600 });
  await rename(temp, path);
}

async function baseFor(directory) {
  if (typeof directory !== 'string' || !isAbsolute(directory) || await realpath(directory) !== directory) throw Error('Invalid project directory');
  const base = join(directory, '.taskboard');
  await safeDirectory(base);
  return base;
}

async function operation(message) {
  const base = await baseFor(message.directory);
  const inbox = join(base, 'inbox');
  if (message.op === 'list') {
    await safeDirectory(inbox);
    await safeDirectory(join(base, 'receipts'));
    const entries = [];
    for (const entry of await readdir(inbox, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      if (entry.isFile() && entry.name.endsWith('.json')) entries.push(join(inbox, entry.name));
      else if (entry.isDirectory()) {
        for (const child of await readdir(join(inbox, entry.name), { withFileTypes: true })) {
          if (child.isFile() && !child.isSymbolicLink() && child.name.endsWith('.json')) entries.push(join(inbox, entry.name, child.name));
        }
      }
    }
    const dated = await Promise.all(entries.map(async path => {
      try { return { path, time: (await lstat(path)).mtimeMs }; }
      catch (error) { if (error.code === 'ENOENT') return null; throw error; }
    }));
    return dated.filter(Boolean).sort((a, b) => a.time - b.time || a.path.localeCompare(b.path)).map(item => item.path);
  }
  if (message.op === 'read') {
    const path = message.path;
    if (typeof path !== 'string' || !within(path, inbox) || !path.endsWith('.json')) return null;
    await safeDirectory(inbox);
    const stat = await lstat(path);
    if (stat.isSymbolicLink() || stat.size > 1_000_000) return null;
    const key = path + ':' + stat.mtimeMs;
    const canonical = await realpath(path);
    if (!within(canonical, inbox)) return null;
    const content = await readFile(path, 'utf8');
    if (Buffer.byteLength(content) > 1_000_000) throw Error('文件桥事件过大');
    return { key, content, receiptName: Buffer.from(path.slice(base.length)).toString('base64url') + '.json' };
  }
  if (typeof message.value !== 'string') throw Error('Invalid file bridge value');
  if (message.op === 'writeReceipt') {
    if (typeof message.receiptName !== 'string' || !/^[A-Za-z0-9_-]+\.json$/.test(message.receiptName)) throw Error('Invalid receipt name');
    const receipts = join(base, 'receipts');
    await safeDirectory(receipts);
    const path = join(receipts, message.receiptName);
    const old = await regularText(path);
    if (old !== message.value) await atomic(path, message.value);
    return { receivedAt: (await lstat(path)).mtime.toISOString() };
  }
  if (message.op === 'writeReporting') {
    const path = join(base, 'REPORTING.md');
    const existing = await regularText(path);
    if (existing === message.value) return { status: 'current', currentText: existing };
    let generatedOld = existing === message.legacy;
    if (existing !== null && !generatedOld) {
      const match = existing.match(generated);
      generatedOld = !!match && Number(match[1]) < message.version &&
        createHash('sha256').update(existing.replace(match[0], marker)).digest('hex') === match[2];
    }
    if (existing !== null && !generatedOld) return { status: 'customized', currentText: existing };
    await atomic(path, message.value);
    return { status: 'current', currentText: message.value };
  }
  if (message.op === 'readRule' || message.op === 'installRule') {
    const name = rulePaths[message.provider];
    if (!name) throw Error('Invalid reporting rule provider');
    const path = join(message.directory, name);
    const current = await regularText(path);
    const installed = current?.includes(message.value) ?? false;
    if (message.op === 'installRule' && !installed) {
      if (current?.includes('<!-- Seqivo reporting rule: begin -->') || current?.includes('<!-- Seqivo reporting rule: end -->'))
        throw Error('已有序程规则标记但内容已修改，请手动处理');
      const next = current === null || current === '' ? message.value + '\n' : current + (current.endsWith('\n') ? '\n' : '\n\n') + message.value + '\n';
      await atomic(path, next);
    }
    return { path: name, installed: message.op === 'installRule' ? true : installed };
  }
  if (message.op === 'writeTasks') { await atomic(join(base, 'tasks.json'), message.value); return true; }
  if (message.op === 'writeContext') { await atomic(join(base, 'CONTEXT.md'), message.value); return true; }
  throw Error('Unsupported file bridge operation');
}

process.on('message', async message => {
  if (!message || !Number.isSafeInteger(message.id)) return;
  try {
    if (!bounded(message)) throw Error('文件桥请求过大');
    const result = await operation(message);
    if (!bounded({ id: message.id, result })) throw Error('文件桥响应过大');
    if (process.connected) process.send({ id: message.id, result });
  } catch (error) {
    if (process.connected) process.send({ id: message.id, error: { message: String(error.message).slice(0, 240), code: error.code } });
  }
});
// A lost parent must not leave a worker alive with filesystem authority.
process.on('disconnect', () => process.kill(process.pid, 'SIGTERM'));

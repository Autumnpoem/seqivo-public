import {chromium,webkit} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,mkdir,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createCore} from '../../server/core.mjs';
import {startHttp} from '../../server/http.mjs';

const engine=process.env.TEST_BROWSER==='webkit'?'webkit':'chromium';
const dir=await mkdtemp(join(tmpdir(),'seqivo-stale-review-'));
const qa=process.env.QA_DIR||join(dir,'evidence');
await mkdir(qa,{recursive:true});
let core,web,browser;
try{
  core=await createCore({dataDir:join(dir,'data'),pluginDir:resolve('plugins'),files:false});
  const project=core.store.project({name:'过期验收草稿复现',goal:'检查版本更新后的验收边界'});
  const created=core.store.createTask({projectId:project.id,title:'待验收交付',goal:'交付当前版本',summary:'旧版交付',criteria:['有对应版本证据']});
  const submitted=core.store.updateTask(created.id,{status:'submitted'},created.revision);
  const original=core.store.addEvidence(created.id,{expectedRevision:submitted.revision,summary:'旧版证据',reference:'v1-report'});
  const localTask=core.store.createTask({projectId:project.id,title:'本地草稿任务',goal:'验证编辑和证据表单',summary:'本地初版',criteria:['有记录']});
  web=await startHttp({core,dataDir:join(dir,'data'),distDir:resolve(process.env.TEST_DIST_DIR||'dist'),port:0});
  browser=await (engine==='webkit'?webkit:chromium).launch({headless:true,...(engine==='chromium'&&process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
  const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
  const page=await context.newPage();
  const pageErrors=[];page.on('pageerror',error=>pageErrors.push(error.message));
  await page.addInitScript(token=>sessionStorage.setItem('taskboard-token',token),web.tokens.owner);
  let commandPosts=0,reviewPayload=null,stateReads=0;
  await page.route('**/api/state',async route=>{
    stateReads++;
    const state=await core.state();
    return route.fulfill({json:{...state,projects:state.projects.map(p=>({...p,inboxAvailable:true})),connection:{...state.connection,mode:'hub',offline:false},capabilities:{...state.capabilities,remote:true,inbox:true,role:'controller'}}});
  });
  await page.route('**/api/commands',route=>{
    commandPosts++;
    reviewPayload=route.request().postDataJSON();
    assert.equal(reviewPayload.action,'review');
    const reviewed=core.store.review(created.id,{expectedRevision:reviewPayload.expectedRevision,...reviewPayload.body});
    return route.fulfill({json:{commandId:reviewPayload.commandId,projectId:project.id,taskId:created.id,action:'review',status:'completed',result:{taskId:created.id,status:'completed',revision:reviewed.revision}}});
  });
  await page.goto(`http://127.0.0.1:${web.port}`);
  const card=page.locator('.inbox-card').filter({has:page.getByRole('heading',{name:'待验收交付'})});
  await card.getByRole('button',{name:'人工验收'}).click();
  const dialog=page.getByRole('dialog',{name:'人工验收'});
  await dialog.getByLabel('验收说明').fill('我检查过旧版交付');
  assert.equal(await dialog.isVisible(),true);
  const readsAtOpen=stateReads;
  await page.waitForFunction(()=>document.querySelector('[role="dialog"]')!==null,{timeout:3000});
  await new Promise(resolve=>setTimeout(resolve,2200));
  assert.ok(stateReads>readsAtOpen,'hub refreshed without changing the task');
  assert.equal(await dialog.getByLabel('验收说明').inputValue(),'我检查过旧版交付');
  assert.equal(await dialog.getByRole('button',{name:'提交结论'}).isEnabled(),true);
  await context.setOffline(true);
  assert.equal(await dialog.getByLabel('验收说明').inputValue(),'我检查过旧版交付','offline did not discard draft');
  await context.setOffline(false);
  await dialog.getByRole('button',{name:'提交结论'}).waitFor();
  await page.waitForFunction(()=>navigator.onLine);
  assert.equal(await dialog.getByLabel('验收说明').inputValue(),'我检查过旧版交付','reconnect did not discard draft');
  const openedRevision=original.revision,openedVersion=original.contentVersion;

  const changed=core.store.updateTask(created.id,{summary:'新版交付',status:'submitted'},original.revision);
  assert.ok(changed.contentVersion>openedVersion);
  assert.throws(()=>core.store.review(created.id,{expectedRevision:openedRevision,decision:'pass',summary:'旧草稿'}),error=>error?.status===409,'store rejects an unchanged stale revision');
  const updated=core.store.addEvidence(created.id,{expectedRevision:changed.revision,summary:'新版证据',reference:'v2-report'});
  await page.getByRole('region',{name:'任务详情'}).getByText('新版交付',{exact:true}).waitFor({timeout:8000});
  assert.equal(await dialog.isVisible(),true,'dialog remains open after refreshed task');
  assert.equal(await dialog.getByLabel('验收说明').inputValue(),'我检查过旧版交付','draft remains unchanged');
  await dialog.getByText('任务内容或记录已更新，请关闭草稿、核对当前版本后重新打开。').waitFor();
  assert.equal(await dialog.getByRole('button',{name:'提交结论'}).isDisabled(),true);
  await dialog.locator('form').evaluate(form=>form.requestSubmit());
  assert.equal(commandPosts,0,'Return/programmatic submit cannot bypass the stale guard');
  await dialog.getByRole('button',{name:'未通过'}).click();
  await dialog.locator('form').evaluate(form=>form.requestSubmit());
  assert.equal(commandPosts,0,'fail review uses the same stale guard');
  assert.notEqual(core.store.getTask(created.id).acceptance,'passed');
  await dialog.getByRole('button',{name:'取消'}).click();
  await page.getByRole('region',{name:'任务详情'}).getByRole('button',{name:'人工验收'}).click();
  await dialog.getByLabel('验收说明').fill('我检查过新版交付');
  await dialog.getByRole('button',{name:'提交结论'}).click();
  await dialog.waitFor({state:'hidden'});
  const final=core.store.getTask(created.id);
  assert.equal(commandPosts,1);
  assert.equal(reviewPayload.expectedRevision,updated.revision,'reopened dialog submitted current revision');
  assert.equal(final.acceptance,'passed','review of current version succeeds after reopening');
  assert.equal(final.review.contentVersion,updated.contentVersion);
  assert.equal(final.review.summary,'我检查过新版交付');
  assert.deepEqual(pageErrors,[]);
  const evidence={engine,opened:{revision:openedRevision,contentVersion:openedVersion,draft:'我检查过旧版交付'},otherSide:{revision:updated.revision,contentVersion:updated.contentVersion,summary:updated.summary,evidence:updated.evidence.at(-1)?.reference},staleCommandPosts:0,submittedAfterReopen:{expectedRevision:reviewPayload.expectedRevision,decision:reviewPayload.body.decision,summary:reviewPayload.body.summary},final:{revision:final.revision,contentVersion:final.contentVersion,acceptance:final.acceptance,review:final.review},commandPosts};
  await writeFile(join(qa,`stale-dialog-${engine}.json`),JSON.stringify(evidence,null,2));
  await page.screenshot({path:join(qa,`stale-dialog-${engine}.png`),fullPage:true,animations:'disabled'});
  await context.close();

  const localContext=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
  const localPage=await localContext.newPage();localPage.on('pageerror',error=>pageErrors.push(error.message));
  await localPage.addInitScript(token=>sessionStorage.setItem('taskboard-token',token),web.tokens.owner);
  let evidencePosts=0,editPatches=0;
  let localStateReads=0;
  await localPage.route('**/api/state',route=>{localStateReads++;return route.continue()});
  async function refreshWithoutVersionChange(dialog){const before=localStateReads;await localPage.evaluate(()=>document.querySelector('button[aria-label="刷新"]')?.click());const deadline=Date.now()+5000;while(localStateReads<=before&&Date.now()<deadline)await new Promise(resolve=>setTimeout(resolve,100));assert.ok(localStateReads>before,'same-version local refresh completed');assert.equal(await dialog.getByRole('button',{name:'保存'}).isEnabled(),true,'same-version refresh keeps submit available');}
  localPage.on('request',request=>{if(request.url().includes(`/api/tasks/${localTask.id}/evidence`)&&request.method()==='POST')evidencePosts++;if(request.url().endsWith(`/api/tasks/${localTask.id}`)&&request.method()==='PATCH')editPatches++;});
  await localPage.goto(`http://127.0.0.1:${web.port}`);
  await localPage.getByRole('navigation',{name:'移动导航'}).getByRole('button',{name:'任务清单'}).click();
  await localPage.locator('.task-row').filter({hasText:'本地草稿任务'}).click();
  const detail=localPage.getByRole('region',{name:'任务详情'});
  await detail.getByRole('button',{name:'添加证据'}).click();
  const evidenceDialog=localPage.getByRole('dialog',{name:'添加证据'});
  await evidenceDialog.getByLabel('证据说明').fill('旧版证据草稿');
  await evidenceDialog.getByLabel('证据引用').fill('old-draft');
  await refreshWithoutVersionChange(evidenceDialog);
  assert.equal(await evidenceDialog.getByLabel('证据说明').inputValue(),'旧版证据草稿');
  const changedLocal=core.store.updateTask(localTask.id,{summary:'本地第二版'},localTask.revision);
  await detail.getByText('本地第二版',{exact:true}).waitFor({timeout:8000});
  await evidenceDialog.getByText('任务内容或记录已更新，请关闭草稿、核对当前版本后重新打开。').waitFor();
  assert.equal(await evidenceDialog.getByLabel('证据说明').inputValue(),'旧版证据草稿');
  assert.equal(await evidenceDialog.getByRole('button',{name:'保存'}).isDisabled(),true);
  await evidenceDialog.locator('form').evaluate(form=>form.requestSubmit());
  assert.equal(evidencePosts,0,'stale evidence draft did not write');
  await evidenceDialog.getByRole('button',{name:'取消'}).click();
  await detail.getByRole('button',{name:'添加证据'}).click();
  await evidenceDialog.getByLabel('证据说明').fill('当前版本证据');
  await evidenceDialog.getByLabel('证据引用').fill('current-report');
  await evidenceDialog.getByRole('button',{name:'保存'}).click();
  await evidenceDialog.waitFor({state:'hidden'});
  assert.equal(evidencePosts,1);
  assert.equal(core.store.getTask(localTask.id).evidence.at(-1)?.reference,'current-report');

  await detail.getByRole('button',{name:'编辑任务'}).click();
  const editDialog=localPage.getByRole('dialog',{name:'编辑任务'});
  await editDialog.getByLabel('当前进展').fill('旧编辑草稿');
  await refreshWithoutVersionChange(editDialog);
  assert.equal(await editDialog.getByLabel('当前进展').inputValue(),'旧编辑草稿');
  const beforeEdit=core.store.getTask(localTask.id);
  core.store.updateTask(localTask.id,{summary:'另一端更新进展'},beforeEdit.revision);
  await detail.getByText('另一端更新进展',{exact:true}).waitFor({timeout:8000});
  await editDialog.getByText('任务内容或记录已更新，请关闭草稿、核对当前版本后重新打开。').waitFor();
  assert.equal(await editDialog.getByLabel('当前进展').inputValue(),'旧编辑草稿');
  assert.equal(await editDialog.getByRole('button',{name:'保存'}).isDisabled(),true);
  await editDialog.locator('form').evaluate(form=>form.requestSubmit());
  assert.equal(editPatches,0,'stale edit draft did not write');
  await editDialog.getByRole('button',{name:'取消'}).click();
  await detail.getByRole('button',{name:'编辑任务'}).click();
  await editDialog.getByLabel('当前进展').fill('核对后的当前进展');
  await editDialog.getByRole('button',{name:'保存'}).click();
  await editDialog.waitFor({state:'hidden'});
  assert.equal(editPatches,1);
  assert.equal(core.store.getTask(localTask.id).summary,'核对后的当前进展');
  assert.deepEqual(pageErrors,[]);
  await localContext.close();
  console.log(`PASS [${engine}]: stale hub review and local evidence/edit blocked; reopening current drafts succeeds`);
}finally{await browser?.close();await web?.close();await core?.close();await rm(dir,{recursive:true,force:true})}

/** Real isolated Core + HTTP + Git + browser UI. No AI provider or terminal writes. */
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {cp,mkdir,mkdtemp,readFile,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {chromium,expect} from '@playwright/test';
import {createCore} from '../../server/core.mjs';
import {startHttp} from '../../server/http.mjs';

const root=await mkdtemp(join(tmpdir(),'seqivo-worktree-live-'));
const repo=join(root,'project'),qa=resolve('design/qa/worktree-live');
const git=(cwd,...args)=>execFileSync('git',['-C',cwd,...args],{encoding:'utf8',timeout:5000}).trim();
const evidence={checks:[],passed:false,realCore:true,realGit:true,realAi:false};
let core,http,browser;
try{
  await mkdir(repo);await mkdir(qa,{recursive:true});
  git(repo,'init','-q','-b','main');git(repo,'config','user.name','Isolated UI Test');git(repo,'config','user.email','worktree-ui@example.test');
  await writeFile(join(repo,'shared.txt'),'base\n');git(repo,'add','.');git(repo,'commit','-qm','base');
  const base=git(repo,'rev-parse','HEAD');
  core=await createCore({dataDir:join(root,'data'),pluginDir:join(root,'empty-plugins'),files:false});
  const project=core.store.project({name:'工作树真实界面',directory:repo});
  const task=core.store.createTask({projectId:project.id,title:'实现共享文件更新',criteria:['核对提交后的共享文件']});
  const appDist=join(root,'web');await cp(resolve('dist'),appDist,{recursive:true});
  http=await startHttp({core,dataDir:join(root,'data'),distDir:appDist,port:0});
  browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
  const context=await browser.newContext({viewport:{width:1100,height:900},serviceWorkers:'block'});
  await context.addInitScript(token=>sessionStorage.setItem('taskboard-token',token),http.tokens.owner);
  const page=await context.newPage(),pageErrors=[];page.on('pageerror',error=>pageErrors.push(error.message));
  async function workflow(){await page.goto(`http://127.0.0.1:${http.port}`);await page.getByRole('navigation',{name:'主要导航'}).getByText('更多功能').click();await page.getByRole('navigation',{name:'主要导航'}).getByRole('button',{name:'协作计划'}).click();await page.getByRole('heading',{name:'独立工作区'}).waitFor();}
  await workflow();
  assert.equal(await page.getByLabel('工作区安排').inputValue(),'project');
  await page.getByText('建立角色工作区').click();
  await page.locator('.worktree-create select').first().selectOption(task.id);
  await page.getByRole('button',{name:'建立工作区'}).click();
  await page.getByText('独立工作区已建立。',{exact:false}).waitFor();
  const entries=await core.request('GET',`/api/worktrees?projectId=${project.id}`,{});
  assert.equal(entries.length,1);const tree=entries[0];
  assert.equal(tree.baseCommit,base);assert.equal(tree.phase,'ready');
  await page.getByRole('button',{name:'在此工作区创建独立会话'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'在此工作区创建独立会话'}).isDisabled(),false);
  // The actual Codex provider is intentionally not invoked. No bound session is invented.
  assert.equal(await page.getByRole('button',{name:'保存草稿'}).isDisabled(),true);
  evidence.checks.push('owner UI created a real Git worktree at the exact project base; no AI session or plan was fabricated');
  await writeFile(join(tree.path,'shared.txt'),'source\n');git(tree.path,'add','.');git(tree.path,'commit','-qm','source');
  const sourceHead=git(tree.path,'rev-parse','HEAD');
  await writeFile(join(repo,'shared.txt'),'target\n');git(repo,'add','.');git(repo,'commit','-qm','target');
  const targetHead=git(repo,'rev-parse','HEAD');
  const submitted=core.store.updateTask(task.id,{status:'submitted'},task.revision);
  const evidenced=core.store.addEvidence(task.id,{summary:'本测试人工核对了隔离提交',reference:`git:${sourceHead}`,expectedRevision:submitted.revision});
  core.store.review(task.id,{decision:'pass',summary:'隔离测试中人工核对源码提交和验收项',expectedRevision:evidenced.revision});
  await workflow();
  await page.getByRole('group',{name:'工作树列表'}).getByRole('button',{name:/实现共享文件更新/}).click();
  await page.locator('.worktree-detail').getByText('查看文件变化与补丁').click();
  await page.getByText('source',{exact:false}).waitFor();
  await page.getByRole('button',{name:'已核对当前差异，登记人工审查'}).click();
  await page.getByText('人工审查已登记到当前源和目标版本。',{exact:false}).waitFor();
  const receipt=core.store.db.prepare('SELECT source_head,target_head FROM worktree_reviews WHERE worktree_id=?').get(tree.id);
  assert.equal(receipt.source_head,sourceHead);assert.equal(receipt.target_head,targetHead);
  await page.getByRole('button',{name:'按审查记录请求合入'}).click();
  await page.getByText('合入冲突待人工解决').waitFor();
  assert.equal(git(repo,'rev-parse','MERGE_HEAD'),sourceHead);
  assert.match(await readFile(join(repo,'shared.txt'),'utf8'),/<<<<<<< HEAD/);
  assert.equal(await page.getByRole('button',{name:'安全清理工作区'}).isDisabled(),true);
  await page.screenshot({path:join(qa,'conflict.png'),fullPage:true});
  evidence.checks.push('real owner review receipt bound exact source/target SHA; Git merge conflict preserved and cleanup stayed disabled');
  const changed=core.store.updateTask(task.id,{summary:'合入前修订验收范围，旧人工验收失效'},core.store.getTask(task.id).revision);
  assert.equal(changed.acceptance,'stale');
  await writeFile(join(repo,'shared.txt'),'combined\n');git(repo,'add','.');
  await page.getByRole('button',{name:'重新检查'}).click();
  await page.getByText('没有未解决的冲突文件。').waitFor();
  const stale=await core.request('GET',`/api/worktrees/${tree.id}`,{});
  assert.deepEqual(stale.reviewStatus,{valid:false,reason:'task_review_stale',reviewId:stale.reviewId});
  const finalize=page.getByRole('button',{name:'已核对暂存差异，完成合入提交'});
  assert.equal(await finalize.isDisabled(),true,'finalize requires opening current staged patch');
  await page.getByText('查看主工作区暂存差异与索引版本').click();
  await page.getByText('combined',{exact:false}).waitFor();
  assert.equal(await finalize.isDisabled(),true,'stale human review remains fenced after viewing staged patch');
  assert.equal(await page.getByRole('button',{name:'已重新验收并核对暂存差异，登记新审查'}).count(),0);
  await page.screenshot({path:join(qa,'stale-review.png'),fullPage:true});
  evidence.checks.push('task content change invalidated human acceptance; current staged patch viewing could not finalize or create indexed review');
  const renewedEvidence=core.store.addEvidence(task.id,{summary:'人工复核了当前内容版本与隔离暂存差异',reference:`git-index:${stale.indexTree}`,expectedRevision:changed.revision});
  core.store.review(task.id,{decision:'pass',summary:'重新核对当前版本和合入前暂存结果',expectedRevision:renewedEvidence.revision});
  await workflow();
  await page.getByRole('group',{name:'工作树列表'}).getByRole('button',{name:/实现共享文件更新/}).click();
  await page.getByText('查看主工作区暂存差异与索引版本').click();
  await page.getByRole('button',{name:'已重新验收并核对暂存差异，登记新审查'}).click();
  await page.getByText('当前暂存版本的人工审查已登记。',{exact:false}).waitFor();
  const indexed=await core.request('GET',`/api/worktrees/${tree.id}`,{});
  assert.equal(indexed.reviewStatus.valid,true);assert.equal(indexed.indexTree,stale.indexTree);
  const indexedReceipt=core.store.db.prepare('SELECT index_tree,content_version FROM worktree_reviews WHERE id=?').get(indexed.reviewStatus.reviewId);
  assert.equal(indexedReceipt.index_tree,stale.indexTree);assert.equal(indexedReceipt.content_version,core.store.getTask(task.id).contentVersion);
  assert.equal(await finalize.isDisabled(),true,'new receipt requires re-viewing the current index');
  await page.getByText('查看主工作区暂存差异与索引版本').click();
  await expect(finalize).toBeEnabled();
  await finalize.click();
  await page.getByText('合入提交已完成。').waitFor();
  assert.equal(git(repo,'show','HEAD:shared.txt'),'combined');
  const merged=await core.request('GET',`/api/worktrees/${tree.id}`,{});assert.equal(merged.phase,'merged');
  await page.getByRole('button',{name:'安全清理工作区'}).click();
  await page.getByText('工作树已安全清理。').waitFor();
  const removed=await core.request('GET',`/api/worktrees/${tree.id}`,{});assert.equal(removed.phase,'removed');
  assert.deepEqual(pageErrors,[]);
  await page.screenshot({path:join(qa,'merged.png'),fullPage:true});
  evidence.checks.push('renewed human acceptance plus exact-index review completed a real merge; only eligible worktree was cleaned');
  evidence.passed=true;
}catch(error){evidence.error=error.message;process.exitCode=1;}
finally{
  await browser?.close();const cleanup=await Promise.allSettled([http?.close(),core?.close()]);
  evidence.cleanShutdown=cleanup.every(item=>item.status==='fulfilled');
  if(!evidence.cleanShutdown){evidence.passed=false;process.exitCode=1;}
  await writeFile(join(qa,'result.json'),JSON.stringify(evidence,null,2));console.log(JSON.stringify(evidence));
  if(evidence.cleanShutdown)await rm(root,{recursive:true,force:true});
}
